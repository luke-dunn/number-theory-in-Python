from itertools import combinations
from math import gcd

for x in range(100):
    for y in range(x):
        for z in range(y):
            for w in range(z):
                nums=(w,z,y,x)
                tot = sum(n**3 for n in nums)
                c = round(tot**(1/3))
                if c**3 == tot and all(gcd(a, b) == 1 for a, b in combinations(nums, 2)):
                    print(nums,c)

